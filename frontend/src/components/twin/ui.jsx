import { useRef, useState } from "react";
import { LEVELS, fmt, useTwin } from "../../lib/twin.js";
import { SAMPLE_ALARMS } from "./sampleAlarms.js";

/** DEMO / LIVE badge. Simulated values are never presented as factory measurements. */
export function SimBadge({ compact = false }) {
  const { source, conn } = useTwin((s) => ({ source: s.snap?.source, conn: s.conn }));
  if (!source) return <span className="simbadge off"><span className="sb-dot" />{conn === "idle" ? "Not connected" : "Connecting…"}</span>;
  const live = source === "LIVE";
  const down = conn !== "live";
  return (
    <span className={`simbadge ${live ? "live" : "sim"}${down ? " down" : ""}`}
          title={live ? "Readings are pushed by a real gateway to /api/twin/ingest."
            : "DEMO: this telemetry is generated by the built-in simulator. It is not a measurement of a real plant."}>
      <span className="sb-dot" />
      {down ? "Reconnecting…" : live ? "LIVE DATA" : compact ? "SIMULATED" : "SIMULATED DATA · demo"}
    </span>
  );
}

/** Small status strip for the top bar. */
export function TwinStatus() {
  const a = useTwin((s) => s.snap?.alerts);
  const live = a?.active > 0;
  return (
    <div className="twin-status">
      <SimBadge compact />
      {live ? (
        <span className={`tchip${a.critical ? " crit" : " warn"}`}>
          {`${a.active} active alert${a.active === 1 ? "" : "s"}${a.critical ? ` · ${a.critical} critical` : ""}`}
        </span>
      ) : (
        <span className="tchip sample" title="Static sample alarms for demonstration. They are not live alerts.">
          {a ? `No live alerts · ${SAMPLE_ALARMS.length} sample` : `${SAMPLE_ALARMS.length} sample alarms`}
        </span>
      )}
    </div>
  );
}

export function LevelPill({ level, label }) {
  return <span className={`lvl lvl-${level}`}><span className="lvl-dot" />{label || LEVELS[level] || "Normal"}</span>;
}

export function SeverityPill({ severity }) {
  const n = { INFO: 0, WARNING: 1, MAJOR: 2, CRITICAL: 3 }[severity] ?? 0;
  return <span className={`lvl lvl-${severity === "INFO" ? "info" : n}`}><span className="lvl-dot" />{severity[0] + severity.slice(1).toLowerCase()}</span>;
}

export function Metric({ label, value, unit, caption, tone, icon, hint }) {
  return (
    <div className={`tmetric${tone != null ? ` lvl-${tone}` : ""}`} title={hint}>
      <div className="tmetric-top">{icon && <span className="tmetric-icon">{icon}</span>}<span>{label}</span></div>
      <div className="tmetric-value">{value}{unit && <small>{unit}</small>}</div>
      {caption && <div className="tmetric-cap">{caption}</div>}
    </div>
  );
}

export function PageHead({ title, sub, children }) {
  return (
    <header className="page-head tpage-head">
      <div><h2>{title}</h2>{sub && <p className="muted">{sub}</p>}</div>
      <div className="page-actions">{children}<SimBadge /></div>
    </header>
  );
}

export function Empty({ title, children }) {
  return <div className="card tempty"><h3>{title}</h3>{children && <p className="muted">{children}</p>}</div>;
}

/**
 * Live line chart. series = [{ name, color, points: [[ms, value], ...] }]. `band` shades the normal range.
 */
export function LineChart({ series, height = 150, band, unit = "", decimals = 1, windowSec }) {
  const W = 640, H = height, padL = 46, padR = 10, padT = 10, padB = 20;
  const wrap = useRef(null);
  const [hover, setHover] = useState(null);
  const all = series.flatMap((s) => s.points);
  if (all.length < 2) return <div className="tchart empty" style={{ height }}>Waiting for data…</div>;
  const t1 = Math.max(...all.map((p) => p[0]));
  const t0 = windowSec ? t1 - windowSec * 1000 : Math.min(...all.map((p) => p[0]));
  let lo = Math.min(...all.map((p) => p[1])), hi = Math.max(...all.map((p) => p[1]));
  if (band) {
    if (band[0] != null) lo = Math.min(lo, band[0]);
    if (band[1] != null) hi = Math.max(hi, band[1]);
  }
  const span = hi - lo || Math.abs(hi) * 0.1 || 1;
  lo -= span * 0.12; hi += span * 0.12;
  const x = (t) => padL + ((t - t0) / (t1 - t0 || 1)) * (W - padL - padR);
  const y = (v) => padT + (1 - (v - lo) / (hi - lo)) * (H - padT - padB);
  const path = (pts) => pts.filter((p) => p[0] >= t0).map((p, i) => `${i ? "L" : "M"}${x(p[0]).toFixed(1)},${y(p[1]).toFixed(1)}`).join(" ");
  const ticks = [lo + (hi - lo) * 0.12 / 1.24, (lo + hi) / 2, hi - (hi - lo) * 0.12 / 1.24];
  const mins = Math.round((t1 - t0) / 60000);
  const first = series[0].points;
  const onMove = (e) => {
    const r = wrap.current.getBoundingClientRect();
    const f = (e.clientX - r.left) / r.width;
    const t = t0 + ((f * W - padL) / (W - padL - padR)) * (t1 - t0);
    let best = null;
    for (const p of first) if (best === null || Math.abs(p[0] - t) < Math.abs(best[0] - t)) best = p;
    setHover(best);
  };
  return (
    <div className="tchart" ref={wrap} onMouseMove={onMove} onMouseLeave={() => setHover(null)}>
      <svg viewBox={`0 0 ${W} ${H}`} role="img" aria-label={`Live trend, last ${mins} minutes`}>
        {band && (
          <rect x={padL} width={W - padL - padR} fill="rgba(34,197,94,.10)"
                y={band[1] != null ? y(band[1]) : padT} height={Math.max(0, (band[0] != null ? y(band[0]) : H - padB) - (band[1] != null ? y(band[1]) : padT))} />
        )}
        {ticks.map((v, i) => (
          <g key={i}>
            <line x1={padL} x2={W - padR} y1={y(v)} y2={y(v)} className="tc-grid" />
            <text x={padL - 6} y={y(v) + 3} textAnchor="end" className="tc-axis">{fmt(v, decimals)}</text>
          </g>
        ))}
        {series.map((s) => <path key={s.name} d={path(s.points)} fill="none" stroke={s.color} strokeWidth="2" strokeLinejoin="round" strokeLinecap="round" />)}
        <text x={padL} y={H - 4} className="tc-axis">{mins > 0 ? `-${mins} min` : "-1 min"}</text>
        <text x={W - padR} y={H - 4} textAnchor="end" className="tc-axis">now</text>
        {hover && <line x1={x(hover[0])} x2={x(hover[0])} y1={padT} y2={H - padB} className="tc-cross" />}
      </svg>
      {hover && (
        <div className="tc-tip" style={{ left: `${(x(hover[0]) / W) * 100}%` }}>
          {series.map((s) => {
            const p = s.points.reduce((b, q) => (b === null || Math.abs(q[0] - hover[0]) < Math.abs(b[0] - hover[0]) ? q : b), null);
            return <div key={s.name}><i style={{ background: s.color }} />{s.name}: <b>{p ? fmt(p[1], decimals) : "-"}{unit ? ` ${unit}` : ""}</b></div>;
          })}
        </div>
      )}
    </div>
  );
}

